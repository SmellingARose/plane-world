function byId(id) { for (const g of goals) if (g.id === id) return g; return null }

// Which goal (and parameter) a script came from: {id, param} or null for a hand-written script.
function detect(source, neuralPreset) {
    if (!source) return null
    if (neuralPreset && source.trim() === neuralPreset.trim()) return { id: "hold", param: undefined }
    const m = /^\/\/ Goal: (\w+)(?: (-?[\d.]+))?/.exec(source)
    if (!m || !byId(m[1])) return null
    return { id: m[1], param: m[2] !== undefined ? Number(m[2]) : undefined }
}

function terms(g) { return g.terms.map(t => t.name) }

